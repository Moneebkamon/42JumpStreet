"""Score REAL phishing URLs (OpenPhish, already downloaded) against REAL popular sites (Tranco), from link text only.

No network lookups, no page opened, threat-feed rule OFF (an empty feed database), so the scorer cannot look the answers up.
  python scripts/run_real_eval.py [--ml] [--benign N] [--seed S]
Writes docs/real-data-eval.md. Read the caveats in the report before quoting any number.
"""
import argparse
import csv
import os
import random
import sqlite3
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
ap = argparse.ArgumentParser()
ap.add_argument("--ml", action="store_true")
ap.add_argument("--benign", type=int, default=1000)
ap.add_argument("--seed", type=int, default=7)
ap.add_argument("--skip", type=int, default=5000, help="ignore the top N Tranco sites (the bundled popular list)")
ap.add_argument("--top", type=int, default=50000, help="sample benign domains from ranks skip+1..top")
args = ap.parse_args()

scratch = ROOT / "data" / "interim"
os.environ.update(FRAUDSHIELD_NETWORK="0", FRAUDSHIELD_AUTH="0", FRAUDSHIELD_ML="1" if args.ml else "0",
                  FRAUDSHIELD_DB=str(scratch / "eval-scratch.db"), FRAUDSHIELD_THREAT_DB=str(scratch / "eval-empty-feed.db"))
(scratch / "eval-empty-feed.db").unlink(missing_ok=True)

from app.engine.pipeline import run_pipeline  # noqa: E402

import json
split = json.loads((ROOT / "backend" / "tests" / "fixtures" / "openphish_split.json").read_text(encoding="utf-8"))
train, test = split["train"], split["test"]  # rule design looked at TRAIN only; TEST was not looked at
phish = train + test
with open(ROOT / "data" / "raw" / "tranco" / "top-1m.csv", encoding="utf-8") as fh:
    top = [row[1] for i, row in zip(range(args.top), csv.reader(fh)) if i >= args.skip]
benign = [f"https://{d}/" for d in random.Random(args.seed).sample(top, args.benign)]


def score(urls: list[str]) -> list[int]:
    return [run_pipeline(u)["score"] for u in urls]


ps, bs = score(phish), score(benign)
pt, pe = ps[:len(train)], ps[len(train):]


def rate(xs: list[int], t: int) -> float:
    return 100 * sum(x >= t for x in xs) / len(xs)


def hist(xs: list[int]) -> str:
    c = Counter(min(x // 10, 9) * 10 for x in xs)
    return " ".join(f"{b}-{b+9}:{c.get(b, 0)}" for b in range(0, 100, 10))


mode = "rules + URL model" if args.ml else "rules only"
worst = [x for x in sorted(zip(bs, benign), reverse=True)[:12] if x[0] >= 30]
missed = [(s, u) for s, u in zip(pe, test) if s < 30][:12]
lines = [f"# Real-data evaluation ({mode})", "",
         "Generated by `scripts/run_real_eval.py`. Link text only: no network lookups, no page opened, threat-feed rule off.", "",
         f"- Phishing: **{len(phish)}** real URLs from OpenPhish (global, English-heavy, one snapshot), split 150 train / 150 test (seed {split['seed']}). Rule changes were designed by looking at the TRAIN half only.",
         f"- Legitimate: **{len(benign)}** home pages sampled at random (seed {args.seed}) from Tranco ranks {args.skip + 1}-{args.top} (the top {args.skip} are in the bundled popular list, so they are excluded to keep the test honest).", "",
         "| Cutoff | Phishing, train half | Phishing, TEST half | All phishing | Legitimate flagged (false alarms) |", "|---|---|---|---|---|"]
for t, name in ((30, "suspicious+ (30)"), (60, "high risk+ (60)"), (80, "likely fraud (80)")):
    lines.append(f"| {name} | {rate(pt, t):.1f}% | {rate(pe, t):.1f}% | {rate(ps, t):.1f}% | {rate(bs, t):.1f}% ({sum(x >= t for x in bs)} of {len(bs)}) |")
lines += ["", f"Score histogram, phishing (all): {hist(ps)}", f"Score histogram, legitimate: {hist(bs)}", "",
          "## Legitimate sites flagged (score 30 or more)", ""] + [f"- {s}: `{u}`" for s, u in worst]
lines += ["", "## Examples of TEST-half phishing URLs scored below 30", ""] + [f"- {s}: `{u}`" for s, u in missed]
lines += ["", "## Caveats (read before quoting)", "",
          "- OpenPhish is global and mostly English-language; it is not a UAE sample. UAE accuracy is **not measured**.",
          "- Legitimate links here are bare home pages of mid-popularity sites (ranks 5,001-50,000): still an easy negative class. Real false alarms come from login/payment pages, "
          "small local businesses and look-alike lures, none of which are in this sample.",
          "- Many phishing URLs sit on compromised or free-hosting domains; text alone cannot separate those from the real host. "
          "The deployed system adds domain age, certificate, threat feed and (staff) page analysis, which this test switches off.",
          "- Rules were tuned on the golden set and then the free-hosting rule and brand list were designed from the TRAIN half only; the test half is the fair number. One snapshot of one feed, so it says little about next month's kits.",
          "- No legitimate free-hosting pages (github.io, vercel.app previews...) are in the benign sample, so the false-alarm cost of the free-hosting rule is NOT measured.",
          "- No confidence intervals; with ~300 per class the uncertainty is a few percentage points."]
out = ROOT / "docs" / ("real-data-eval-ml.md" if args.ml else "real-data-eval.md")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines[:14]))
