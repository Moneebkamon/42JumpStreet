"""Score the golden set offline (link text only, no network, no page opened) and write docs/golden-report.md.

  python scripts/run_golden.py            # rules only (what the tests use)
  python scripts/run_golden.py --ml       # with the ready URL model switched on
"""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
os.environ["FRAUDSHIELD_NETWORK"] = "0"
os.environ["FRAUDSHIELD_AUTH"] = "0"
os.environ["FRAUDSHIELD_ML"] = "1" if "--ml" in sys.argv else "0"
os.environ["FRAUDSHIELD_DB"] = str(ROOT / "data" / "interim" / "golden-scratch.db")  # keep the real settings out of it

from app.engine.pipeline import run_pipeline  # noqa: E402

FLAG = 30  # "suspicious" or worse counts as flagged


def evaluate() -> dict:
    cases = json.loads((ROOT / "backend" / "tests" / "fixtures" / "golden_urls.json").read_text(encoding="utf-8"))["cases"]
    rows = []
    for c in cases:
        r = run_pipeline(c["url"])
        rows.append({**c, "score": r["score"], "band": r["band"], "flagged": r["score"] >= FLAG})
    phish = [r for r in rows if r["truth"] == "phish"]
    legit = [r for r in rows if r["truth"] != "phish"]
    caught = [r for r in phish if r["flagged"]]
    false_alarms = [r for r in legit if r["flagged"]]
    return {"rows": rows, "phish": len(phish), "caught": len(caught), "legit": len(legit),
            "false_alarms": false_alarms, "missed": [r for r in phish if not r["flagged"]]}


def report(e: dict, mode: str) -> str:
    out = [f"# Golden set report ({mode})", "",
           "Generated by `scripts/run_golden.py`. Link text only: no network lookups, no page opened.", "",
           "**Read this first.** 32 hand-labelled links, written before looking at scores, but the rules were tuned by the same person, "
           "so this is a development check, not an accuracy measurement. Most phishing-style links use made-up domains that a real "
           "attacker would not necessarily choose. Do not quote these numbers as product accuracy.", "",
           f"- Phishing-style links flagged (score >= {FLAG}): **{e['caught']} of {e['phish']}**",
           f"- Legitimate links flagged (false alarms): **{len(e['false_alarms'])} of {e['legit']}**", ""]
    if e["missed"]:
        out += ["## Missed phishing-style links", ""] + [f"- `{r['url']}` scored {r['score']} ({r['note']})" for r in e["missed"]] + [""]
    if e["false_alarms"]:
        out += ["## False alarms", ""] + [f"- `{r['url']}` scored {r['score']} ({r['note']})" for r in e["false_alarms"]] + [""]
    out += ["## All cases", "", "| Truth | Score | Band | Link |", "|---|---|---|---|"]
    out += [f"| {r['truth']} | {r['score']} | {r['band']} | `{r['url']}` |" for r in e["rows"]]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    e = evaluate()
    mode = "rules plus URL model" if "--ml" in sys.argv else "rules only"
    text = report(e, mode)
    if "--ml" not in sys.argv:
        (ROOT / "docs" / "golden-report.md").write_text(text, encoding="utf-8")
    print(text.split("## All cases")[0])
